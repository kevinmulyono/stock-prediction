import argparse
import logging
import os
import sys
from datetime import datetime
from typing import List, Optional
import pandas as pd
import yfinance as yf

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger(__name__)

# Default Universe (Liquid IDX Bluechips; can be customized via CLI)
DEFAULT_TICKERS = [
    "BBCA.JK",  # Bank Central Asia (Financials)
    "BBRI.JK",  # Bank Rakyat Indonesia (Financials)
    "BMRI.JK",  # Bank Mandiri (Financials)
    "TLKM.JK",  # Telkom Indonesia (Infrastructure / Telco)
    "ASII.JK",  # Astra International (Industrials / Conglomerate)
]

DEFAULT_START_DATE = "2018-01-01"
DEFAULT_END_DATE = "2026-09-02"


def fetch_ticker_data(
    ticker: str,
    start_date: str,
    end_date: str
) -> Optional[pd.DataFrame]:
    """
    Fetch OHLCV historical market data for a single ticker using yfinance.
    
    Parameters:
    -----------
    ticker : str
        Stock ticker symbol (e.g. 'BBCA.JK', 'AAPL')
    start_date : str
        Start date formatted as 'YYYY-MM-DD'
    end_date : str
        End date formatted as 'YYYY-MM-DD'
        
    Returns:
    --------
    pd.DataFrame or None
        Raw OHLCV data with DatetimeIndex, or None if download failed/empty.
    """
    logger.info(f"Downloading data for {ticker} from {start_date} to {end_date}...")
    try:
        df = yf.download(
            tickers=ticker,
            start=start_date,
            end=end_date,
            interval="1d",
            auto_adjust=False,  # Keep both Close and Adj Close distinct
            progress=False
        )
        
        if df.empty:
            logger.warning(f"No data returned for ticker: {ticker}")
            return None
            
        # Handle potential MultiIndex columns generated by newer yfinance versions
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)
            
        # Reset index to have 'Date' as a regular column
        df.reset_index(inplace=True)
        
        # Add ticker identifier column
        df["Ticker"] = ticker
        
        logger.info(f"Successfully fetched {len(df)} records for {ticker}.")
        return df

    except Exception as e:
        logger.error(f"Error fetching data for {ticker}: {str(e)}")
        return None


def collect_market_data(
    tickers: List[str],
    start_date: str,
    end_date: str,
    output_dir: str = "data/raw"
) -> pd.DataFrame:
    """
    Fetch market data for a list of tickers and save each to data/raw/ as CSV.
    Also produces an ingestion summary metadata DataFrame.
    """
    os.makedirs(output_dir, exist_ok=True)
    summary_records = []
    
    for ticker in tickers:
        df = fetch_ticker_data(ticker, start_date, end_date)
        
        if df is not None and not df.empty:
            # Clean filename by replacing special characters (e.g. BBCA.JK -> BBCA_JK.csv)
            safe_ticker_name = ticker.replace(".", "_")
            output_filepath = os.path.join(output_dir, f"{safe_ticker_name}_raw.csv")
            
            # Save raw unedited CSV
            df.to_csv(output_filepath, index=False)
            logger.info(f"Saved raw data to {output_filepath}")
            
            min_date = df["Date"].min()
            max_date = df["Date"].max()
            total_rows = len(df)
            
            summary_records.append({
                "ticker": ticker,
                "status": "SUCCESS",
                "total_rows": total_rows,
                "first_date": str(min_date)[:10],
                "last_date": str(max_date)[:10],
                "output_file": output_filepath,
                "collected_at": datetime.now().isoformat()
            })
        else:
            summary_records.append({
                "ticker": ticker,
                "status": "FAILED",
                "total_rows": 0,
                "first_date": None,
                "last_date": None,
                "output_file": None,
                "collected_at": datetime.now().isoformat()
            })
            
    summary_df = pd.DataFrame(summary_records)
    summary_path = os.path.join(output_dir, "collection_summary.csv")
    summary_df.to_csv(summary_path, index=False)
    logger.info(f"Ingestion summary saved to {summary_path}")
    
    return summary_df


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Track A - Stock Market Data Ingestion Pipeline")
    parser.add_argument(
        "--tickers",
        nargs="+",
        default=DEFAULT_TICKERS,
        help="List of tickers to fetch (e.g. --tickers BBCA.JK BBRI.JK BMRI.JK)"
    )
    parser.add_argument(
        "--start",
        default=DEFAULT_START_DATE,
        help="Start date (YYYY-MM-DD)"
    )
    parser.add_argument(
        "--end",
        default=DEFAULT_END_DATE,
        help="End date (YYYY-MM-DD)"
    )
    parser.add_argument(
        "--output-dir",
        default="data/raw",
        help="Target raw data directory"
    )
    
    args = parser.parse_args()
    
    logger.info("=== Starting Data Collection Pipeline (Track A) ===")
    summary = collect_market_data(
        tickers=args.tickers,
        start_date=args.start,
        end_date=args.end,
        output_dir=args.output_dir
    )
    print("\nCollection Summary Report:")
    print(summary.to_string(index=False))
