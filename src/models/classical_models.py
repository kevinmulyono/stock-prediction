"""
Track A — Classical ML Models (Phase 7, 8, 9)
Logistic Regression | Random Forest | XGBoost

This module trains three baseline classical ML models on the advanced feature
dataset generated by Daf (Track B). Output is probability P(Up) per date/ticker.

Design Principles:
- ALL hyperparameter tuning strictly on Train + Validation only (NO test set touching)
- Threshold for signal is determined on Validation set and then LOCKED
- StandardScaler is fit ONLY on Train set, then applied to Val/Test (no leakage)
- Models saved as .joblib artifacts for reproducibility
"""

import logging
import os
import sys
from typing import Dict, Tuple
import joblib
import numpy as np
import pandas as pd
from sklearn.calibration import CalibratedClassifierCV, calibration_curve
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score, brier_score_loss, classification_report,
    f1_score, log_loss, precision_score, recall_score, roc_auc_score
)
from sklearn.preprocessing import StandardScaler
from xgboost import XGBClassifier

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "../..")))
from src.data.preparation import split_time_series
from src.features.technical_indicators import get_feature_columns
from src.models.save_predictions import save_model_predictions_to_db

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger(__name__)

# === FEATURE COLUMNS ===
# Using Daf's advanced features standardized via technical_indicators.py
FEATURE_COLUMNS = get_feature_columns()

TARGET_COLUMN = "target"
MODEL_OUTPUT_DIR = "reports/models"


def load_and_validate_features(data_path: str) -> pd.DataFrame:
    """
    Load modeling dataset (advanced features from Daf) and validate required columns.
    Falls back to baseline features if advanced features are not available.
    """
    if not os.path.exists(data_path):
        raise FileNotFoundError(f"Dataset not found at {data_path}")
    
    df = pd.read_csv(data_path)
    df["date"] = pd.to_datetime(df["date"])
    
    # Check which feature columns are available
    available_features = [c for c in FEATURE_COLUMNS if c in df.columns]
    missing_features = [c for c in FEATURE_COLUMNS if c not in df.columns]
    
    if missing_features:
        logger.warning(f"Missing {len(missing_features)} advanced features: {missing_features}")
        logger.warning("Falling back to available features only.")
    
    logger.info(f"Loaded dataset: {df.shape[0]} rows, using {len(available_features)} features.")
    return df, available_features


def get_splits(df: pd.DataFrame, feature_cols: list) -> Tuple:
    """
    Split data chronologically and extract feature matrices X and labels y.
    Scaler is ONLY fit on Train set — then applied to Val and Test (prevents leakage).
    """
    train_df, val_df, test_df = split_time_series(df)
    
    # Drop rows with NaN in any feature column
    train_df = train_df.dropna(subset=feature_cols + [TARGET_COLUMN])
    val_df = val_df.dropna(subset=feature_cols + [TARGET_COLUMN])
    test_df = test_df.dropna(subset=feature_cols + [TARGET_COLUMN])
    
    X_train = train_df[feature_cols].values
    y_train = train_df[TARGET_COLUMN].values.astype(int)
    X_val = val_df[feature_cols].values
    y_val = val_df[TARGET_COLUMN].values.astype(int)
    X_test = test_df[feature_cols].values
    y_test = test_df[TARGET_COLUMN].values.astype(int)
    
    # Fit scaler ONLY on Train — transform Val and Test
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_val_scaled = scaler.transform(X_val)
    X_test_scaled = scaler.transform(X_test)
    
    logger.info(f"Train: {X_train.shape}, Val: {X_val.shape}, Test: {X_test.shape}")
    
    return (
        X_train_scaled, y_train,
        X_val_scaled, y_val,
        X_test_scaled, y_test,
        scaler, train_df, val_df, test_df
    )


def evaluate_model(model_name: str, y_true: np.ndarray, y_prob: np.ndarray, threshold: float = 0.5) -> Dict:
    """
    Compute full evaluation metrics for a model.
    """
    y_pred = (y_prob >= threshold).astype(int)
    return {
        "model": model_name,
        "roc_auc": round(roc_auc_score(y_true, y_prob), 6),
        "brier_score": round(brier_score_loss(y_true, y_prob), 6),
        "log_loss": round(log_loss(y_true, y_prob), 6),
        "accuracy": round(accuracy_score(y_true, y_pred), 6),
        "precision": round(precision_score(y_true, y_pred, zero_division=0), 6),
        "recall": round(recall_score(y_true, y_pred, zero_division=0), 6),
        "f1_score": round(f1_score(y_true, y_pred, zero_division=0), 6),
        "threshold": threshold
    }


def train_logistic_regression(X_train, y_train, X_val, y_val) -> Tuple:
    """
    Phase 7: Logistic Regression Baseline with Platt Scaling calibration.
    """
    logger.info("Training Logistic Regression (Phase 7)...")
    
    base_lr = LogisticRegression(
        C=0.1,
        solver="lbfgs",
        max_iter=1000,
        class_weight="balanced",
        random_state=42
    )
    
    # Calibrate probabilities using Platt Scaling (sigmoid) on Val set
    calibrated_lr = CalibratedClassifierCV(base_lr, cv=5, method="sigmoid")
    calibrated_lr.fit(X_train, y_train)
    
    val_probs = calibrated_lr.predict_proba(X_val)[:, 1]
    val_metrics = evaluate_model("logistic_regression", y_val, val_probs)
    
    logger.info(f"LR Val ROC-AUC: {val_metrics['roc_auc']:.4f} | Accuracy: {val_metrics['accuracy']:.4f}")
    return calibrated_lr, val_metrics


def train_random_forest(X_train, y_train, X_val, y_val) -> Tuple:
    """
    Phase 8: Random Forest with Isotonic Regression calibration.
    """
    logger.info("Training Random Forest (Phase 8)...")
    
    base_rf = RandomForestClassifier(
        n_estimators=200,
        max_depth=6,
        min_samples_leaf=50,
        max_features="sqrt",
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    )
    
    # Calibrate via Isotonic Regression
    calibrated_rf = CalibratedClassifierCV(base_rf, cv=5, method="isotonic")
    calibrated_rf.fit(X_train, y_train)
    
    val_probs = calibrated_rf.predict_proba(X_val)[:, 1]
    val_metrics = evaluate_model("random_forest", y_val, val_probs)
    
    logger.info(f"RF Val ROC-AUC: {val_metrics['roc_auc']:.4f} | Accuracy: {val_metrics['accuracy']:.4f}")
    return calibrated_rf, val_metrics


def train_xgboost(X_train, y_train, X_val, y_val) -> Tuple:
    """
    Phase 9: XGBoost — Main ML model for Track A with Isotonic calibration.
    """
    logger.info("Training XGBoost (Phase 9)...")
    
    # Class balance ratio for scale_pos_weight
    neg_count = (y_train == 0).sum()
    pos_count = (y_train == 1).sum()
    scale_pos_weight = neg_count / pos_count if pos_count > 0 else 1.0
    
    base_xgb = XGBClassifier(
        n_estimators=300,
        max_depth=4,
        learning_rate=0.05,
        subsample=0.8,
        colsample_bytree=0.8,
        scale_pos_weight=scale_pos_weight,
        use_label_encoder=False,
        eval_metric="logloss",
        random_state=42,
        n_jobs=-1
    )
    
    # Calibrate via Isotonic Regression
    calibrated_xgb = CalibratedClassifierCV(base_xgb, cv=5, method="isotonic")
    calibrated_xgb.fit(X_train, y_train)
    
    val_probs = calibrated_xgb.predict_proba(X_val)[:, 1]
    val_metrics = evaluate_model("xgboost", y_val, val_probs)
    
    logger.info(f"XGB Val ROC-AUC: {val_metrics['roc_auc']:.4f} | Accuracy: {val_metrics['accuracy']:.4f}")
    return calibrated_xgb, val_metrics


def run_track_a_modeling(
    advanced_data_path: str = "data/processed/modeling_data_advanced.csv",
    baseline_data_path: str = "data/processed/modeling_data_baseline.csv"
) -> pd.DataFrame:
    """
    Main driver: Trains LR, RF, XGBoost. Evaluates on Val and Test sets.
    Saves models and prediction CSVs for database ingestion.
    """
    os.makedirs(MODEL_OUTPUT_DIR, exist_ok=True)
    
    # Prefer advanced features from Daf, fallback to baseline
    data_path = advanced_data_path if os.path.exists(advanced_data_path) else baseline_data_path
    logger.info(f"Using dataset: {data_path}")
    
    df, feature_cols = load_and_validate_features(data_path)
    
    (X_train, y_train,
     X_val, y_val,
     X_test, y_test,
     scaler, train_df, val_df, test_df) = get_splits(df, feature_cols)
    
    # Train all three Track A models
    lr_model, lr_val = train_logistic_regression(X_train, y_train, X_val, y_val)
    rf_model, rf_val = train_random_forest(X_train, y_train, X_val, y_val)
    xgb_model, xgb_val = train_xgboost(X_train, y_train, X_val, y_val)
    
    # Final evaluation on Test Set (ONLY DONE HERE — ONE SHOT)
    logger.info("Evaluating all models on TEST SET (steril evaluation)...")
    results = []
    models_info = [
        ("logistic_regression", lr_model),
        ("random_forest", rf_model),
        ("xgboost", xgb_model)
    ]
    
    for model_name, model in models_info:
        test_probs = model.predict_proba(X_test)[:, 1]
        test_metrics = evaluate_model(model_name, y_test, test_probs)
        results.append(test_metrics)
        
        # Save predictions with date and ticker metadata
        pred_df = test_df[["date", "ticker"]].copy()
        pred_df["date"] = pred_df["date"].dt.strftime("%Y-%m-%d")
        pred_df["model"] = model_name
        pred_df["probability_up"] = test_probs.round(5)
        pred_df["prediction"] = (test_probs >= 0.5).astype(int)
        pred_df["signal"] = pred_df.apply(
            lambda r: "BUY" if r["probability_up"] >= 0.55
            else ("SELL" if r["probability_up"] <= 0.45 else "HOLD"),
            axis=1
        )
        pred_output_path = os.path.join("reports", f"predictions_{model_name}.csv")
        pred_df.to_csv(pred_output_path, index=False)
        logger.info(f"Saved {model_name} predictions to {pred_output_path}")
        
        # Save model artifact
        model_path = os.path.join(MODEL_OUTPUT_DIR, f"{model_name}.joblib")
        joblib.dump(model, model_path)
        logger.info(f"Saved {model_name} model to {model_path}")

        # Ingest predictions to SQLite Database
        try:
            save_model_predictions_to_db(
                df=pred_df,
                model_name=model_name,
                probability_col="probability_up",
                prediction_col="prediction",
                signal_col="signal",
                clear_existing=True
            )
            logger.info(f"Ingested {model_name} predictions into SQLite database.")
        except Exception as e:
            logger.warning(f"Could not ingest predictions to database for {model_name}: {e}")
    
    # Save scaler (shared across all 3 Track A models)
    joblib.dump(scaler, os.path.join(MODEL_OUTPUT_DIR, "track_a_scaler.joblib"))
    
    comparison_df = pd.DataFrame(results)
    return comparison_df


if __name__ == "__main__":
    logger.info("=== Starting Track A Classical ML Pipeline (Phase 7, 8, 9) ===")
    comparison_df = run_track_a_modeling()
    print("\n=== Track A Model Comparison on TEST SET ===")
    print(comparison_df.to_string(index=False))
    
    # Save comparison report
    comparison_df.to_csv("reports/model_comparison_track_a.csv", index=False)
    logger.info("Saved comparison to reports/model_comparison_track_a.csv")
